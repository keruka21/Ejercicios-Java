/*Crea un programa con un método llamado 'saludar' que muestre por pantalla el mensaje
 '¡Hola, bienvenidos a Java!'. Llama al método desde el main.
*/

public class Ej1EstaticosSaludo {

    public static void saludar() {
        System.out.println("¡Hola, bienvenidos a Java!");
    }

    public static void main(String[] args) {
        saludar();
    }
}