package ud02;
/*Documento Word Bucles - Ejercicio 1:
Transforma el siguiente bucle for a un bucle while:
for (i = 5; i<15; i++)
{
System.out.println(i);
}
*/

public class Bucles1 {

	 public static void main(String[] args) {
		 
		 //Declaración de variables
		 int i=5;
		  
		 while (i<=15) {
			 System.out.println(i);
			 i++;
		 }
	 }
}